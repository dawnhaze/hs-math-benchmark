def render(template: str, **kwargs: object) -> str:
    """安全填充提示词模板。

    刻意不用 str.format —— 提示词里嵌着大段 JSON schema，花括号会被
    format 当成占位符，是个很容易踩的坑（本项目自检就抓到过一次）。
    """
    out = template
    for key, value in kwargs.items():
        out = out.replace(f"<<{key.upper()}>>", str(value))
    return out
